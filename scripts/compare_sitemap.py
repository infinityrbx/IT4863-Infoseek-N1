"""Compare the crawl (site_count) with the sitemap (sitemap_urls) for T2.

    python scripts/compare_sitemap.py
    python scripts/compare_sitemap.py --crawl output/site_count_pages.jsonl --sitemap output/sitemap_urls.jsonl

Prints set sizes, overlap and a capture-recapture (Lincoln-Petersen) estimate of the
total number of content pages:  N ~= |crawl| * |sitemap| / |crawl & sitemap|.
That estimate assumes both "samples" are independent, which they are not quite (the
sitemap is generated by the CMS, the crawl only reaches linked pages), so report it as
a rough figure next to the raw counts. Writes the differences to output/only_in_*.txt.
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from ircrawler.urlnorm import page_key as normalize_url  # noqa: E402


def load(path, skip_flagged=False):
    urls = set()
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            rec = json.loads(line)
            if skip_flagged and rec.get("skip_reason"):
                continue
            urls.add(normalize_url(rec.get("canonical") or rec["url"]))
            if rec.get("canonical"):
                urls.add(normalize_url(rec["url"]))
    return urls


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--crawl", default="output/site_count_pages.jsonl")
    ap.add_argument("--sitemap", default="output/sitemap_urls.jsonl")
    ap.add_argument("--outdir", default="output")
    a = ap.parse_args()

    crawl = load(a.crawl)
    sitemap = load(a.sitemap, skip_flagged=True)
    both = crawl & sitemap
    print(f"crawl content pages      : {len(crawl)}")
    print(f"sitemap URLs (filtered)  : {len(sitemap)}")
    print(f"in both                  : {len(both)}")
    print(f"only in crawl            : {len(crawl - sitemap)}")
    print(f"only in sitemap          : {len(sitemap - crawl)}")
    print(f"union                    : {len(crawl | sitemap)}")
    if both:
        print(f"Lincoln-Petersen estimate: {len(crawl) * len(sitemap) / len(both):.0f}")
    else:
        print("Lincoln-Petersen estimate: n/a (no overlap)")
    out = Path(a.outdir)
    out.mkdir(exist_ok=True)
    (out / "only_in_crawl.txt").write_text("\n".join(sorted(crawl - sitemap)), encoding="utf-8")
    (out / "only_in_sitemap.txt").write_text("\n".join(sorted(sitemap - crawl)), encoding="utf-8")


if __name__ == "__main__":
    main()
